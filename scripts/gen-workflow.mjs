// Rebuilds .github/workflows/reminders.yml from reminders.json.  Run: node scripts/gen-workflow.mjs
import fs from 'node:fs';
import { OFFSETS, cronFor } from './schedule.mjs';
const cfg = JSON.parse(fs.readFileSync(new URL('../reminders.json', import.meta.url)));
const crons = [...new Set(cfg.reminders.filter(r => r.on).flatMap(r => OFFSETS.map(o => cronFor(r.time, o))))].sort();
const yml = `# Generated by scripts/gen-workflow.mjs from reminders.json. Don't edit by hand.
name: reminders
on:
${crons.length ? '  schedule:\n' + crons.map(c => `    - cron: '${c}'`).join('\n') + '\n' : ''}  workflow_dispatch:
    inputs:
      test:
        description: 'Send a test notification now'
        type: boolean
        default: true
permissions:
  contents: read
concurrency: reminders
jobs:
  send:
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - run: npm install --no-save --no-audit --no-fund web-push@3.6.7
      - run: node scripts/send-reminders.mjs
        env:
          PUSH_CONFIG: \${{ secrets.PUSH_CONFIG }}
          SCHEDULE: \${{ github.event.schedule }}
          TEST: \${{ github.event_name == 'workflow_dispatch' && inputs.test }}
`;
fs.writeFileSync(new URL('../.github/workflows/reminders.yml', import.meta.url), yml);
console.log(`Wrote ${crons.length} schedule lines for ${cfg.reminders.filter(r => r.on).length} reminders.`);
